#!/usr/bin/env python3
"""Prototipteki (prototype/index.html) metin tabanlı sprite tablolarını Unity'deki
SpriteData.cs dosyasına aktarır. Böylece iki taraf aynı çizimleri kullanır.

Kullanım:  python3 tools/export_sprites.py
"""
import json
import re

SRC = "prototype/index.html"
DST = "unity/PixTrain/Assets/_Project/Scripts/Render/SpriteData.cs"
NAMES = ["LOCO_STEAM", "TENDER", "TREE", "PINE", "PALM", "BUSH", "FLOWERS", "ROCK", "ROCKB", "LOGS", "COW", "COW2",
         "SHEEP", "CAR", "LAMP", "BARRIER", "BOAT", "LIGHTHOUSE", "MILL", "WARN"]
ARROW_NAMES = {"0": "ArrowStraight", "'-1'": "ArrowLeft", "1": "ArrowRight"}


def js_json(text: str):
    return json.loads(re.sub(r",\s*([\]}])", r"\1", text))


def main() -> None:
    src = open(SRC, encoding="utf-8").read()
    out = ["// <auto-generated>",
           "// prototype/index.html içindeki sprite tablolarından tools/export_sprites.py ile üretildi. Elle düzenlemeyin.",
           "// </auto-generated>",
           "namespace PixTrain.Render",
           "{",
           "    internal static class SpriteData",
           "    {"]

    def emit(name, rows):
        out.append(f"        public static readonly string[] {name} =")
        out.append("        {")
        out.extend(f'            "{r}",' for r in rows)
        out.append("        };")
        out.append("")

    for n in NAMES:
        m = re.search(r"const " + n + r" = (\[.*?\]);", src, re.S)
        emit("".join(p.capitalize() for p in n.lower().split("_")), js_json(m.group(1)))

    coin = js_json(re.search(r"const COIN = (\[.*?\]\]);", src, re.S).group(1))
    for i, rows in enumerate(coin):
        emit(f"Coin{i}", rows)

    icons = re.search(r"const ICONS = \{(.*?)\n\};", src, re.S).group(1)
    for m in re.finditer(r"(\w+): (\[.*?\]),", icons):
        emit("Icon" + m.group(1)[0].upper() + m.group(1)[1:], js_json(m.group(2)))

    arrows = re.search(r"const ARROWS = \{(.*?)\n\};", src, re.S).group(1)
    for m in re.finditer(r"('?-?\d'?): (\[.*?\]),", arrows):
        emit(ARROW_NAMES[m.group(1)], js_json(m.group(2)))

    if out[-1] == "":
        out.pop()
    out.extend(["    }", "}"])
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(DST)


if __name__ == "__main__":
    main()
